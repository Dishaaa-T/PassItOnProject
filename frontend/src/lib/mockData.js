export function filterMockProducts(params) {
  let products = [...mockProducts];

  if (params.category) {
    products = products.filter((p) => p.category === params.category);
  }
  if (params.condition) {
    products = products.filter((p) => p.condition === params.condition);
  }
  if (params.search) {
    const q = String(params.search).toLowerCase();
    products = products.filter(
      (p) =>
        p.title.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q)
    );
  }
  if (params.minPrice) {
    products = products.filter((p) => p.price >= Number(params.minPrice));
  }
  if (params.maxPrice) {
    products = products.filter((p) => p.price <= Number(params.maxPrice));
  }

  if (params.sort === 'price-low') products.sort((a, b) => a.price - b.price);
  if (params.sort === 'price-high') products.sort((a, b) => b.price - a.price);

  return {
    products,
    page: 1,
    pages: 1,
    total: products.length,
  };
}

export function getMockProductById(id) {
  return mockProducts.find((p) => p._id === id);
}

export function getMockRelatedProducts(id) {
  const product = mockProducts.find((p) => p._id === id);
  if (!product) return [];
  return mockProducts
    .filter((p) => p._id !== id && p.category === product.category)
    .slice(0, 4);
}
